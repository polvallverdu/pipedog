// Package discovery for the compat harness: finds workspace packages, their
// public entries (package.json "exports") and their smoke test, and rewrites
// the `pipecat.runtimes` field from measured results.

import { existsSync, readFileSync, realpathSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { Glob } from "bun";

export const RUNTIMES = ["bun", "node", "deno", "workerd"] as const;
export type Runtime = (typeof RUNTIMES)[number];

export const ROOT = resolve(import.meta.dir, "../..");

export interface PackageInfo {
  name: string;
  dir: string;
  pkgJsonPath: string;
  pkgJson: Record<string, any>;
  /** Absolute path of `compat/smoke.ts`, or null to use the default import smoke test. */
  smoke: string | null;
}

export interface PublicEntry {
  /** Specifier a consumer would import, e.g. `@pipedog/core/frames/frames`. */
  specifier: string;
  /** Absolute path of the file it resolves to. */
  file: string;
}

export async function discoverPackages(): Promise<PackageInfo[]> {
  const out: PackageInfo[] = [];
  for await (const rel of new Glob("packages/*/package.json").scan(ROOT)) {
    const pkgJsonPath = join(ROOT, rel);
    const dir = join(pkgJsonPath, "..");
    const pkgJson = await Bun.file(pkgJsonPath).json();
    const smokePath = join(dir, "compat", "smoke.ts");
    out.push({
      name: pkgJson.name,
      dir,
      pkgJsonPath,
      pkgJson,
      smoke: existsSync(smokePath) ? smokePath : null,
    });
  }
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

/** Pick the file target of an exports value (a string or a conditions object). */
function exportTarget(value: unknown): string | null {
  if (typeof value === "string") return value;
  if (value && typeof value === "object") {
    const v = value as Record<string, unknown>;
    for (const key of ["import", "default", "bun", "node"]) {
      const t = exportTarget(v[key]);
      if (t) return t;
    }
  }
  return null;
}

/**
 * Enumerate every public entry of a package. `"./*"` patterns are expanded by
 * listing the files that match the target pattern (e.g. `./src/*.ts`).
 */
export async function publicEntries(pkg: PackageInfo): Promise<PublicEntry[]> {
  let exportsField = pkg.pkgJson.exports;
  if (exportsField == null) exportsField = { ".": pkg.pkgJson.module ?? pkg.pkgJson.main };
  if (typeof exportsField === "string") exportsField = { ".": exportsField };
  const entries: PublicEntry[] = [];
  const seen = new Set<string>();
  const add = (specifier: string, file: string) => {
    if (seen.has(file)) return;
    seen.add(file);
    entries.push({ specifier, file });
  };
  for (const [key, value] of Object.entries(exportsField as Record<string, unknown>)) {
    const target = exportTarget(value);
    if (!target || key.endsWith("package.json")) continue;
    const sub = key === "." ? "" : key.slice(1);
    if (!key.includes("*")) {
      add(pkg.name + sub, join(pkg.dir, target));
      continue;
    }
    const [tPre, tSuf] = target.split("*") as [string, string];
    const [kPre, kSuf] = sub.split("*") as [string, string];
    const base = join(pkg.dir, tPre);
    if (!existsSync(base)) continue;
    for await (const f of new Glob(`**/*${tSuf}`).scan(base)) {
      if (f.endsWith(".d.ts") || f.includes("node_modules")) continue;
      const star = f.slice(0, f.length - tSuf.length);
      add(`${pkg.name}${kPre}${star}${kSuf}`, join(base, f));
    }
  }
  return entries.sort((a, b) => a.specifier.localeCompare(b.specifier));
}

/**
 * Write the default smoke module (imports every public entry) and return its path.
 * It is plain JS so every runtime can load it without type stripping.
 */
export async function writeDefaultSmoke(pkg: PackageInfo, dir: string): Promise<string> {
  const entries = await publicEntries(pkg);
  if (entries.length === 0) throw new Error(`${pkg.name}: no public entries in package.json`);
  const lines = ["// Generated by tools/compat: imports every public entry."];
  entries.forEach((e, i) => {
    lines.push(`import * as m${i} from ${JSON.stringify(e.file)};`);
  });
  lines.push("const modules = [");
  entries.forEach((e, i) => {
    lines.push(`  [${JSON.stringify(e.specifier)}, m${i}],`);
  });
  lines.push("];");
  lines.push("export default async function smoke() {");
  lines.push("  for (const [name, mod] of modules) {");
  lines.push(
    `    if (typeof mod !== "object" || mod === null) throw new Error("bad module " + name);`,
  );
  lines.push("  }");
  lines.push("}");
  const path = join(dir, "default-smoke.mjs");
  await Bun.write(path, `${lines.join("\n")}\n`);
  return path;
}

/**
 * Set `pipecat.runtimes` from measured results. Runtimes that were not tested
 * in this run keep their current state. Formatting: 2-space JSON + newline.
 */
export async function writeRuntimes(
  pkg: PackageInfo,
  results: Partial<Record<Runtime, boolean>>,
): Promise<string[]> {
  const json = await Bun.file(pkg.pkgJsonPath).json();
  const current: string[] = json.pipecat?.runtimes ?? [];
  const runtimes = RUNTIMES.filter((rt) => (rt in results ? results[rt] : current.includes(rt)));
  json.pipecat = { ...(json.pipecat ?? {}), runtimes };
  await Bun.write(pkg.pkgJsonPath, `${JSON.stringify(json, null, 2)}\n`);
  return runtimes;
}

/**
 * Optional peer dependencies to hide while testing `pkg`: every optional peer
 * declared by a workspace package (e.g. core's `@opentelemetry/api`), except
 * those `pkg` itself requires (a dependency or a non-optional peer). This is
 * what a consumer who never installed the optional peers sees.
 */
export function optionalPeersToHide(pkg: PackageInfo, all: PackageInfo[]): string[] {
  const optional = new Set<string>();
  for (const p of all) {
    const meta = (p.pkgJson.peerDependenciesMeta ?? {}) as Record<string, { optional?: boolean }>;
    for (const [name, m] of Object.entries(meta)) if (m?.optional) optional.add(name);
  }
  const own = pkg.pkgJson;
  const ownMeta = (own.peerDependenciesMeta ?? {}) as Record<string, { optional?: boolean }>;
  // Optional peers this package's users are expected to install (e.g. an ONNX
  // runtime for the ONNX packages), declared in package.json as
  // "pipecat": { "compat": { "usesOptionalPeers": [...] } }. Not hidden.
  const uses = ((own.pipecat as { compat?: { usesOptionalPeers?: string[] } } | undefined)?.compat
    ?.usesOptionalPeers ?? []) as string[];
  const required = new Set<string>([
    ...Object.keys(own.dependencies ?? {}),
    ...Object.keys(own.peerDependencies ?? {}).filter((n) => !ownMeta[n]?.optional),
    ...uses,
  ]);
  // A required dependency may itself depend on an optional peer (e.g.
  // @google/genai on `ws`): that module is installed for everyone, so keep it.
  for (const n of installedDependencies(pkg.dir, required)) required.add(n);
  return [...optional].filter((n) => !required.has(n)).sort();
}

/** Package directory of `name` as resolved from `fromDir`, or null when not installed. */
function findPackageDir(name: string, fromDir: string): string | null {
  for (let dir = fromDir; ; dir = dirname(dir)) {
    const candidate = join(dir, "node_modules", name, "package.json");
    if (existsSync(candidate)) return dirname(realpathSync(candidate));
    if (dirname(dir) === dir) return null;
  }
}

/** Names of every package reachable through `dependencies` of `roots` (installed ones only). */
function installedDependencies(fromDir: string, roots: Iterable<string>): Set<string> {
  const names = new Set<string>();
  const seen = new Set<string>();
  const queue: [string, string][] = [...roots].map((n) => [n, fromDir]);
  while (queue.length > 0) {
    const [name, from] = queue.pop() as [string, string];
    const dir = findPackageDir(name, from);
    if (!dir || seen.has(dir)) continue;
    seen.add(dir);
    names.add(name);
    const json = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    for (const dep of Object.keys(json.dependencies ?? {})) queue.push([dep, dir]);
  }
  return names;
}

export function rel(p: string): string {
  return relative(ROOT, p);
}
