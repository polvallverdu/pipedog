// Generate porting/STATUS.md (progress per package + runtime compatibility)
// from porting/manifest.json and each package's `pipecat.runtimes`.
//
// Usage: bun tools/port/status.ts [--set <module|test file> <status> [notes]]

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

type Status = "todo" | "in_progress" | "ported" | "tested" | "skipped";
interface Mod {
  module: string;
  package: string;
  ts: string;
  lines: number;
  status: Status;
  mvp: boolean;
  notes: string;
  portedAt?: string | null;
  layer: number;
}
interface TestEntry {
  file: string;
  package: string;
  ts: string;
  lines: number;
  status: Status;
  notes: string;
}
interface Manifest {
  upstreamCommit: string;
  modules: Mod[];
  tests: TestEntry[];
}

const manifestPath = "porting/manifest.json";
const manifest: Manifest = JSON.parse(readFileSync(manifestPath, "utf8"));

const args = process.argv.slice(2);
if (args[0] === "--set") {
  const [, key, status, ...notes] = args;
  const entry =
    manifest.modules.find((m) => m.module === key || m.ts === key) ??
    manifest.tests.find((t) => t.file === key || t.ts === key);
  if (!entry || !status)
    throw new Error(`usage: --set <module|test> <status> [notes]; unknown ${key}`);
  entry.status = status as Status;
  if (notes.length) entry.notes = notes.join(" ");
  if ("module" in entry && status !== "todo") entry.portedAt = manifest.upstreamCommit;
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
}

// --sync-tests: run every ported test file and record its real status.
if (args[0] === "--sync-tests") {
  for (const t of manifest.tests) {
    if (!existsSync(t.ts)) continue;
    const proc = Bun.spawnSync(["bun", "test", t.ts], { stdout: "pipe", stderr: "pipe" });
    const out = `${proc.stdout.toString()}${proc.stderr.toString()}`;
    const count = (k: string) => Number(new RegExp(`(\\d+) ${k}`).exec(out)?.[1] ?? 0);
    const [pass, fail, skip, todo] = [count("pass"), count("fail"), count("skip"), count("todo")];
    // Failures: re-port. Todos: blocked on an unported module. Only skips: skipped upstream/deprecated.
    t.status =
      fail > 0 || pass + skip + todo === 0
        ? "in_progress"
        : todo > 0
          ? "ported"
          : pass === 0
            ? "skipped"
            : skip > 0
              ? "ported"
              : "tested";
    t.notes = `${pass} pass, ${fail} fail, ${skip} skip, ${todo} todo`;
    console.log(`${t.status.padEnd(12)} ${t.ts} (${t.notes})`);
  }
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
}

const done = (s: Status) => s === "ported" || s === "tested" || s === "skipped";
const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}%` : "–");

const packages = new Map<string, { mods: Mod[]; tests: TestEntry[] }>();
for (const m of manifest.modules) {
  if (!packages.has(m.package)) packages.set(m.package, { mods: [], tests: [] });
  packages.get(m.package)!.mods.push(m);
}
for (const t of manifest.tests) {
  if (!packages.has(t.package)) packages.set(t.package, { mods: [], tests: [] });
  packages.get(t.package)!.tests.push(t);
}

const runtimesOf = (pkg: string): string[] => {
  const file = `packages/${pkg.split("/")[1]}/package.json`;
  if (!existsSync(file)) return [];
  return JSON.parse(readFileSync(file, "utf8")).pipecat?.runtimes ?? [];
};
const RUNTIMES = ["bun", "node", "deno", "workerd"];

const mvp = manifest.modules.filter((m) => m.mvp);
const lines: string[] = [
  "# Porting status",
  "",
  `Upstream: pipecat-ai/pipecat@\`${manifest.upstreamCommit.slice(0, 10)}\`. Generated by \`bun run port:status\`; do not edit.`,
  "",
  `**Milestone 1 (core runtime):** ${mvp.filter((m) => done(m.status)).length}/${mvp.length} modules ` +
    `(${pct(
      mvp.filter((m) => done(m.status)).reduce((a, m) => a + m.lines, 0),
      mvp.reduce((a, m) => a + m.lines, 0),
    )} of lines).`,
  "",
  `| Package | Modules | Lines ported | Tests | ${RUNTIMES.join(" | ")} |`,
  `|---|---|---|---|${RUNTIMES.map(() => "---").join("|")}|`,
];
const sorted = [...packages.entries()].sort((a, b) =>
  a[0] === "@pipecat-ts/core" ? -1 : b[0] === "@pipecat-ts/core" ? 1 : a[0].localeCompare(b[0]),
);
for (const [pkg, { mods, tests }] of sorted) {
  const total = mods.reduce((a, m) => a + m.lines, 0);
  const ported = mods.filter((m) => done(m.status)).reduce((a, m) => a + m.lines, 0);
  const rts = runtimesOf(pkg);
  lines.push(
    `| \`${pkg}\` | ${mods.filter((m) => done(m.status)).length}/${mods.length} | ${pct(ported, total)} | ` +
      `${tests.filter((t) => done(t.status)).length}/${tests.length} | ` +
      RUNTIMES.map((r) => (rts.includes(r) ? "✅" : "")).join(" | ") +
      " |",
  );
}

// Packages we wrote that have no upstream counterpart.
const extra = readdirSync("packages").filter((d) => !packages.has(`@pipecat-ts/${d}`));
if (extra.length) {
  lines.push(
    "",
    "Packages without an upstream counterpart: " +
      extra.map((d) => `\`@pipecat-ts/${d}\``).join(", "),
  );
}
const notes = manifest.modules.filter((m) => m.notes);
if (notes.length) {
  lines.push("", "## Notes", "", ...notes.map((m) => `- \`${m.module}\`: ${m.notes}`));
}
writeFileSync("porting/STATUS.md", `${lines.join("\n")}\n`);
console.log(lines.slice(0, 6).join("\n"));
