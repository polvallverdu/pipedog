"""Write THIRD_PARTY_LICENSES.md for a package that bundles compiled Rust code.

Lists every crate in the normal-dependency tree of the package's Rust crate
(wasm32 target) with its SPDX license and the license text from the crate's own
source. Dual-licensed crates (MIT OR Apache-2.0, ...) are used under the first
option we include the text of (MIT where offered).

Usage: python3 -I tools/release/third_party_licenses.py packages/<name>
"""

import json
import os
import subprocess
import sys

PREFERRED = ["LICENSE-MIT", "LICENSE-MIT.md", "LICENSE.md", "LICENSE", "LICENSE.txt", "COPYING",
             "UNLICENSE", "LICENSE-ZLIB", "LICENSE-APACHE", "LICENSE-UNICODE"]


def license_texts(crate_dir, spdx):
    files = sorted(os.listdir(crate_dir))
    picked = []
    for name in PREFERRED:
        if name in files:
            picked.append(name)
            if name.startswith("LICENSE-MIT") or name in ("LICENSE", "LICENSE.md", "LICENSE.txt"):
                break
    if "Unicode-3.0" in (spdx or "") and "LICENSE-UNICODE" in files and "LICENSE-UNICODE" not in picked:
        picked.append("LICENSE-UNICODE")
    if not picked:
        picked = [f for f in files if f.upper().startswith(("LICENSE", "COPYING", "UNLICENSE"))][:2]
    return [(name, open(os.path.join(crate_dir, name), encoding="utf-8", errors="replace").read().strip())
            for name in picked]


def main():
    pkg = sys.argv[1].rstrip("/")
    rust = os.path.join(pkg, "rust")
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--filter-platform", "wasm32-unknown-unknown"],
        cwd=rust, capture_output=True, text=True, check=True).stdout)
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    pkgs = {p["id"]: p for p in meta["packages"]}
    root = meta["resolve"]["root"]
    seen, stack = set(), [root]
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k.get("kind") in (None, "normal") for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    crates = sorted((pkgs[i] for i in seen if i != root), key=lambda p: (p["name"], p["version"]))

    out = [
        "# Third-party licenses",
        "",
        f"The WebAssembly module in this package is compiled from the Rust crate in `rust/` and the",
        f"crates below. Generated by `tools/release/third_party_licenses.py`; do not edit.",
        "",
    ]
    for p in crates:
        crate_dir = os.path.dirname(p["manifest_path"])
        out += [f"## {p['name']} {p['version']}", "", f"License: `{p.get('license')}`  ",
                f"Source: {p.get('repository') or 'https://crates.io/crates/' + p['name']}", ""]
        texts = license_texts(crate_dir, p.get("license"))
        if not texts:
            raise SystemExit(f"no license file found for {p['name']} {p['version']} in {crate_dir}")
        for name, text in texts:
            out += [f"<details><summary>{name}</summary>", "", "```text", text, "```", "", "</details>", ""]
    path = os.path.join(pkg, "THIRD_PARTY_LICENSES.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"{path}: {len(crates)} crates")


if __name__ == "__main__":
    main()
