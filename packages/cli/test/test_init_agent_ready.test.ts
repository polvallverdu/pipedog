// Tests for `pipedog init`: initializing a project (AGENTS.md + CLAUDE.md).
//
// DIVERGENCE: the questions are scripted through a `Prompter` (upstream stubs questionary), the
// directory prompt of a bare `init` runs only on a terminal (a piped `init` writes the guide into
// the current directory), and the guide text is pipedog's. The quickstart README has no Context
// Hub section: the docs MCP server is registered by `init` itself.

import { describe, expect, test } from "bun:test";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { cli, read, ScriptedPrompter, tmpDir } from "./helpers.ts";

const AGENT_TEMPLATES = join(import.meta.dir, "..", "agent_templates");
const template = (name: string) => readFileSync(join(AGENT_TEMPLATES, name), "utf8");

describe("TestInitAgentReady", () => {
  // Behavior of the `pipedog init` file-drop command.

  test("test_writes_all_files", async () => {
    const target = tmpDir();
    const result = await cli(["init", target]);
    expect(result.code, result.output).toEqual(0);
    expect(read(target, "AGENTS.md").trim()).not.toEqual("");
    expect(read(target, "AGENTS.md")).toContain("pipedog init");
    expect(read(target, "CLAUDE.md").trim()).toEqual("@AGENTS.md");
    // Developer guidance: prompt-writing help with a copyable example prompt.
    const gettingStarted = read(target, "GETTING_STARTED.md");
    expect(gettingStarted).toContain("first prompt");
    expect(gettingStarted).toContain("help me choose");
    // The terminal output points the developer at it.
    expect(result.output).toContain("GETTING_STARTED.md");
  });

  test("test_getting_started_preserved_then_refreshed_with_flag", async () => {
    // GETTING_STARTED.md is kept on a plain re-run; --overwrite-guide refreshes it.
    const target = tmpDir();
    await cli(["init", target]);
    writeFileSync(join(target, "GETTING_STARTED.md"), "my notes");
    // Plain re-run preserves the developer's file.
    let result = await cli(["init", target]);
    expect(result.code, result.output).toEqual(0);
    expect(read(target, "GETTING_STARTED.md")).toEqual("my notes");
    // --overwrite-guide rewrites it from the template, version-stamped.
    result = await cli(["init", target, "--overwrite-guide"]);
    expect(result.code, result.output).toEqual(0);
    const text = read(target, "GETTING_STARTED.md");
    expect(text).toContain("first prompt");
    expect(text).toContain("@pipedog/cli 9.9.9");
    expect(text.trimEnd().endsWith("-->")).toBe(true);
  });

  test("test_agents_file_carries_version_stamp", async () => {
    // The written guide ends with a provenance footer naming the writing version.
    const target = tmpDir();
    const result = await cli(["init", target]);
    expect(result.code, result.output).toEqual(0);
    const text = read(target, "AGENTS.md");
    expect(text.trimEnd().endsWith("-->")).toBe(true);
    expect(text).toContain("@pipedog/cli 9.9.9");
    expect(text).toContain("Run `pipedog init --overwrite-guide` to refresh");
    // The bundled template itself stays unstamped: the version is known only at write time.
    expect(template("AGENTS.md")).not.toContain("Generated by");
  });

  test("test_prompts_for_directory_when_omitted", async () => {
    // Bare `init` prompts (on a terminal); the typed value is just a path: it becomes the folder.
    const cwd = tmpDir();
    const prompter = new ScriptedPrompter(["mybot", "agent"]);
    const result = await cli(["init"], { cwd, interactive: true, prompter });
    expect(result.code, result.output).toEqual(0);
    expect(existsSync(join(cwd, "mybot", "AGENTS.md"))).toBe(true);
  });

  test("test_prompt_dot_sets_up_current_dir", async () => {
    const cwd = tmpDir();
    const prompter = new ScriptedPrompter([".", "agent"]);
    const result = await cli(["init"], { cwd, interactive: true, prompter });
    expect(result.code, result.output).toEqual(0);
    expect(existsSync(join(cwd, "AGENTS.md"))).toBe(true);
  });

  test("test_creates_missing_target_dir", async () => {
    const target = join(tmpDir(), "nested", "bot");
    const result = await cli(["init", target]);
    expect(result.code, result.output).toEqual(0);
    expect(existsSync(join(target, "AGENTS.md"))).toBe(true);
  });

  test("test_rerun_preserves_existing_guides", async () => {
    const target = tmpDir();
    await cli(["init", target]);
    writeFileSync(join(target, "AGENTS.md"), "my agents");
    writeFileSync(join(target, "CLAUDE.md"), "# my own claude config");
    const result = await cli(["init", target]);
    expect(result.code, result.output).toEqual(0);
    // Preserve-by-default: a plain re-run clobbers neither file.
    expect(read(target, "AGENTS.md")).toEqual("my agents");
    expect(read(target, "CLAUDE.md")).toEqual("# my own claude config");
  });

  test("test_rerun_summary_when_all_kept", async () => {
    const target = tmpDir();
    await cli(["init", target]);
    // Second run: everything is present and current, so nothing is (re)written.
    const result = await cli(["init", target]);
    expect(result.code, result.output).toEqual(0);
    expect(result.output).toContain("Kept");
    expect(result.output).toContain("already in place");
    expect(result.output).toContain("overwrite-guide");
  });

  test("test_overwrite_guide_overwrites_all", async () => {
    const target = tmpDir();
    await cli(["init", target]);
    writeFileSync(join(target, "AGENTS.md"), "stale agents");
    writeFileSync(join(target, "CLAUDE.md"), "# my own claude config");
    const result = await cli(["init", target, "--overwrite-guide"]);
    expect(result.code, result.output).toEqual(0);
    // Both are replaced with the current templates.
    expect(read(target, "AGENTS.md")).toContain("pipedog init");
    expect(read(target, "CLAUDE.md").trim()).toEqual("@AGENTS.md");
  });

  test("test_scaffold_flags_build_in_place", async () => {
    // Scaffold flags build the project in place (no redirect to a separate command).
    const target = tmpDir();
    const result = await cli([
      "init",
      target,
      "--bot-type",
      "web",
      "-t",
      "smallwebrtc",
      "-m",
      "cascade",
      "--stt",
      "deepgram_stt",
      "--llm",
      "openai_llm",
      "--tts",
      "cartesia_tts",
    ]);
    expect(result.code, result.output).toEqual(0);
    // init initialized for agent-led dev and scaffolded a runnable bot in the same dir.
    expect(existsSync(join(target, "AGENTS.md"))).toBe(true);
    expect(existsSync(join(target, "server", "bot.ts"))).toBe(true);
    // The scaffold path skips the from-scratch developer guide.
    expect(existsSync(join(target, "GETTING_STARTED.md"))).toBe(false);
  });

  test("test_stale_guide_nudges", async () => {
    const target = tmpDir();
    await cli(["init", target]);
    // Simulate a guide written by an older pipedog via an old version stamp.
    const stale = "# old guide\n<!-- Generated by `pipedog init` (@pipedog/cli 0.0.1). -->\n";
    writeFileSync(join(target, "AGENTS.md"), stale);
    const result = await cli(["init", target]);
    expect(result.code, result.output).toEqual(0);
    // Kept as is, but the developer is told it's stale and how to refresh.
    expect(read(target, "AGENTS.md")).toEqual(stale);
    expect(result.output).toContain("0.0.1");
    expect(result.output).toContain("overwrite-guide");
  });

  test("test_stale_guide_offers_refresh_interactively", async () => {
    const target = tmpDir();
    await cli(["init", target]);
    const stale = "# old\n<!-- Generated by `pipedog init` (@pipedog/cli 0.0.1). -->\n";
    writeFileSync(join(target, "AGENTS.md"), stale);
    // Force interactive, confirm the refresh, then pick the default build method.
    const prompter = new ScriptedPrompter([true, "agent"]);
    const result = await cli(["init", target], { interactive: true, prompter });
    expect(result.code, result.output).toEqual(0);
    expect(prompter.asked[0]).toContain("Refresh the guide files");
    // Confirming overwrote the stale guide with the current template.
    expect(read(target, "AGENTS.md")).toContain("pipedog init");
  });

  test("test_stale_guide_refresh_declined_keeps_file", async () => {
    const target = tmpDir();
    await cli(["init", target]);
    const stale = "# old\n<!-- Generated by `pipedog init` (@pipedog/cli 0.0.1). -->\n";
    writeFileSync(join(target, "AGENTS.md"), stale);
    const prompter = new ScriptedPrompter([false, "agent"]);
    const result = await cli(["init", target], { interactive: true, prompter });
    expect(result.code, result.output).toEqual(0);
    // Declining leaves the developer's file untouched.
    expect(read(target, "AGENTS.md")).toEqual(stale);
  });

  test("test_quickstart_scaffolds_and_writes_guide", async () => {
    // `init quickstart` is the human front door for the canned bot: it scaffolds the quickstart
    // in place AND drops the agent guide, all in ./pipedog-quickstart.
    const cwd = tmpDir();
    const result = await cli(["init", "quickstart"], { cwd });
    expect(result.code, result.output).toEqual(0);
    const project = join(cwd, "pipedog-quickstart");
    // Coding-agent guide files...
    expect(existsSync(join(project, "AGENTS.md"))).toBe(true);
    expect(read(project, "CLAUDE.md").trim()).toEqual("@AGENTS.md");
    // ...plus a runnable bot in the same directory.
    expect(existsSync(join(project, "server", "bot.ts"))).toBe(true);
  });

  test("test_quickstart_omits_developer_guide", async () => {
    // GETTING_STARTED.md is from-scratch onboarding; the prebuilt quickstart skips it. Its one
    // still-useful piece (the docs MCP server) is in the scaffold's README.
    const cwd = tmpDir();
    const result = await cli(["init", "quickstart"], { cwd });
    expect(result.code, result.output).toEqual(0);
    const project = join(cwd, "pipedog-quickstart");
    expect(existsSync(join(project, "GETTING_STARTED.md"))).toBe(false);
    expect(read(project, "README.md")).toContain("@pipedog/mcp");
  });

  test("test_target_is_a_file_errors", async () => {
    const dir = tmpDir();
    const file = join(dir, "afile");
    writeFileSync(file, "x");
    const result = await cli(["init", file]);
    expect(result.code).toEqual(1);
    expect(result.output).toContain("not a directory");
  });
});

describe("TestBuildMethodRouting", () => {
  // Interactive `init` routes the developer to a coding agent or an in-place scaffold.

  test("test_scaffold_branch_scaffolds_in_place", async () => {
    const target = tmpDir();
    // The wizard's answers (see test_init_interactive.test.ts): a default web/cascade bot.
    const prompter = new ScriptedPrompter([
      "scaffold",
      "default",
      "web",
      "none",
      "smallwebrtc",
      false,
      "cascade",
      "deepgram_stt",
      "openai_llm",
      "cartesia_tts",
      "bun",
      false,
      false,
      false,
    ]);
    const result = await cli(["init", target], { interactive: true, prompter });
    expect(result.code, result.output).toEqual(0);
    // The scaffold lands in init's target dir, in place, named after it.
    expect(existsSync(join(target, "server", "bot.ts"))).toBe(true);
    // Scaffolding ends in a built bot, so the from-scratch developer guide is skipped: its place
    // is taken by the scaffold's README.
    expect(existsSync(join(target, "GETTING_STARTED.md"))).toBe(false);
    // ...but the core coding-agent guide files are still written.
    expect(existsSync(join(target, "AGENTS.md"))).toBe(true);
    expect(existsSync(join(target, "CLAUDE.md"))).toBe(true);
  });

  test("test_agent_branch_does_not_scaffold", async () => {
    const target = tmpDir();
    const result = await cli(["init", target], {
      interactive: true,
      prompter: new ScriptedPrompter(["agent"]),
    });
    expect(result.code, result.output).toEqual(0);
    expect(result.output.toLowerCase()).toContain("your project is ready");
    expect(existsSync(join(target, "server"))).toBe(false);
    // The coding-agent path gets the developer guide.
    expect(existsSync(join(target, "GETTING_STARTED.md"))).toBe(true);
  });

  test("test_question_skipped_when_already_scaffolded", async () => {
    // Re-running init to refresh the guide in a scaffolded project must not offer to scaffold.
    const target = tmpDir();
    mkdirSync(join(target, "server"));
    const prompter = new ScriptedPrompter([]);
    const result = await cli(["init", target], { interactive: true, prompter });
    expect(result.code, result.output).toEqual(0);
    expect(prompter.asked).toEqual([]);
    expect(existsSync(join(target, "AGENTS.md"))).toBe(true);
  });

  test("test_no_prompt_without_a_tty", async () => {
    // Without a terminal init stays a pure file-drop.
    const target = tmpDir();
    const prompter = new ScriptedPrompter([]);
    const result = await cli(["init", target], { prompter });
    expect(result.code, result.output).toEqual(0);
    expect(prompter.asked).toEqual([]);
    expect(existsSync(join(target, "AGENTS.md"))).toBe(true);
    expect(existsSync(join(target, "server"))).toBe(false);
  });
});

