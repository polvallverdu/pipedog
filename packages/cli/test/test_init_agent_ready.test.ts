describe("TestBundledGuide", () => {
  // The guide must ship and be release-clean (catches packaging + content regressions).

  test("test_bundled_files_exist", () => {
    for (const file of ["AGENTS.md", "CLAUDE.md", "GETTING_STARTED.md"]) {
      expect(existsSync(join(AGENT_TEMPLATES, file))).toBe(true);
    }
  });

  test("test_agents_content_is_release_clean", () => {
    const text = template("AGENTS.md");
    expect(text.trim()).not.toEqual("");
    expect(text).toContain("pipedog init");
    // No local-checkout paths or Pipecat's commands should ever ship.
    expect(text).not.toContain("/Users/");
    expect(text).not.toContain("pipecat create");
    expect(text).not.toContain("pipecat init");
    expect(text).not.toContain("TODO(release)");
  });

  test("test_claude_is_agents_import", () => {
    expect(template("CLAUDE.md").trim()).toEqual("@AGENTS.md");
  });

  test("test_getting_started_is_release_clean", () => {
    const text = template("GETTING_STARTED.md");
    expect(text.trim()).not.toEqual("");
    // No local-checkout paths, and the template ships unstamped (the provenance footer is
    // appended at write time).
    expect(text).not.toContain("/Users/");
    expect(text).not.toContain("Generated by");
  });

  test("NEW: the guides point at pipedog's docs and MCP server, not Pipecat's tools", () => {
    for (const name of ["AGENTS.md", "GETTING_STARTED.md"]) {
      const text = template(name);
      expect(text).toContain("https://polvallverdu.github.io/pipedog/llms.txt");
      expect(text).toContain("@pipedog/mcp");
      expect(text).not.toContain("context-hub");
      expect(text).not.toContain("Context Hub");
      expect(text).not.toContain("pipecat-ai");
      expect(text).not.toContain("uv ");
      expect(text).not.toContain("pcc-deploy");
    }
    expect(template("AGENTS.md")).toContain("npx -y @pipedog/mcp");
  });

  test("NEW: the commands the guide gives are ones the CLI has", async () => {
    // Every flag the guide shows to `pipedog init` is a real flag.
    const help = (await cli(["init", "--help"])).stdout;
    const text = template("AGENTS.md");
    for (const flag of text.match(/--[a-z][a-z-]+/g) ?? []) {
      if (["--dry-run", "--list-options", "--help"].includes(flag)) continue;
      // Flags of other commands that appear in the guide.
      if (["--scope", "--live", "--host", "--proxy", "--no-mcp"].includes(flag)) continue;
      if (flag.startsWith("--no-")) continue;
      expect(help, flag).toContain(flag);
    }
  });
});
