/**
 * `pipedog init`: the single starting point for building a pipedog app.
 *
 * `pipedog init` initializes a new pipedog project, then routes you to a build method:
 *
 * - `AGENTS.md`: the coding-agent guide (read natively by most coding agents).
 * - `CLAUDE.md`: a one-line `@AGENTS.md` import so Claude Code loads it too.
 * - `GETTING_STARTED.md`: for the *developer*: how to drive the agent well (the docs MCP
 *   server, how to write the first prompt, what to expect in a session). Deliberately not in
 *   CLAUDE.md/AGENTS.md: those cost agent context every session, and this guidance is for the
 *   human. Written only on the coding-agent path: it's onboarding for commissioning a build, so
 *   it doesn't fit a project that's already been scaffolded (where the README is the
 *   start-here).
 *
 * `init` is also the scaffolder. After writing AGENTS.md + CLAUDE.md it either:
 *
 * - builds the project from flags or a config file when any scaffold option is given
 *   (`pipedog init . --bot-type web -t smallwebrtc ...`): the non-interactive path coding agents
 *   and automation use;
 * - or, interactively, asks how you want to build: hand off to a coding agent, or scaffold a
 *   runnable bot right now (the wizard, in place in the same directory).
 *
 * `pipedog init quickstart` skips the question and scaffolds the canned quickstart bot in place:
 * the coding-agent guide *and* a runnable bot in one step. The scaffolding itself lives in
 * `scaffold.ts`.
 *
 * Editing policy for the bundled guide: keep API specifics (signatures, imports, parameter
 * names) out of AGENTS.md: it is a static snapshot, so anything that churns belongs in the live
 * sources the guide's §3 points agents at.
 *
 * DIVERGENCE: upstream registers the Pipecat Context Hub (`--context-hub`, a subprocess, plus a
 * 900 MB index it offers to build). This registers `@pipedog/mcp` for Claude Code, Cursor and VS
 * Code by writing the project's MCP config files (`--mcp`, on by default, on every path that
 * writes the guide; see `mcp_register.ts`), and there is no index to build. The arguments are
 * parsed with `node:util`'s `parseArgs` instead of typer, with `--no-<flag>` negations spelled
 * out. The guide files are read from the package's `agent_templates/` directory.
 */

