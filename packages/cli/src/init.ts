/** The parsed command line of `pipedog init`. */
export interface InitArgs {
  target: string | null;
  overwriteGuide: boolean;
  /** Register the MCP server (default true). */
  mcp: boolean;
  mcpClients: McpClient[] | undefined;
  dryRun: boolean;
  listOptions: boolean;
  help: boolean;
  config: string | null;
  flags: ScaffoldFlags;
  /** The scaffold flags (`SCAFFOLD_FLAG_NAMES`) that were typed. */
  explicit: Set<string>;
}

/** Thrown for a bad command line: reported with the usage hint, exit code 2. */
export class UsageError extends Error {
  override name = "UsageError";
}

/**
 * Parse `pipedog init`'s arguments.
 *
 * @throws UsageError For an unknown flag, a missing value or a second target.
 */
export function parseInitArgs(argv: readonly string[]): InitArgs {
  let parsed: ReturnType<
    typeof parseArgs<{ options: typeof INIT_OPTIONS; allowPositionals: true; tokens: true }>
  >;
  try {
    parsed = parseArgs({
      args: [...argv],
      options: INIT_OPTIONS,
      allowPositionals: true,
      tokens: true,
    });
  } catch (e) {
    throw new UsageError(e instanceof Error ? e.message : String(e));
  }
  if (parsed.positionals.length > 1) {
    throw new UsageError(
      `Got unexpected extra arguments (${parsed.positionals.slice(1).join(" ")})`,
    );
  }

  // Toggles: the last of --x / --no-x wins.
  const toggle = new Map<string, boolean>();
  const explicit = new Set<string>();
  for (const token of parsed.tokens ?? []) {
    if (token.kind !== "option") continue;
    const name = token.name;
    const base =
      name.startsWith("no-") && (TOGGLES as readonly string[]).includes(name.slice(3))
        ? name.slice(3)
        : name;
    if ((TOGGLES as readonly string[]).includes(base)) {
      toggle.set(base, base === name);
    }
    // `--eval` sets `enableEval`, as upstream's `--eval/--no-eval` does.
    const flagName = base === "eval" ? "enableEval" : camel(base);
    if ((SCAFFOLD_FLAG_NAMES as readonly string[]).includes(flagName)) explicit.add(flagName);
  }

  const v = parsed.values as Record<string, string | boolean | string[] | undefined>;
  const str = (name: string) => v[name] as string | undefined;
  const flag = (name: string) => toggle.get(name);

  // Pipecat-only flags: the positive form is rejected, with a reason.
  const unsupported: Record<string, unknown> = {};
  if (str("daily-pstn-mode") !== undefined) unsupported.dailyPstnMode = str("daily-pstn-mode");
  if (str("twilio-daily-sip-mode") !== undefined) {
    unsupported.twilioDailySipMode = str("twilio-daily-sip-mode");
  }
  if (flag("deploy-to-cloud") === true) unsupported.deployToCloud = true;
  if (flag("enable-krisp") === true) unsupported.enableKrisp = true;
  if (flag("context-hub") === true) {
    throw new UsageError(
      "--context-hub isn't available: pipedog registers @pipedog/mcp, see --mcp",
    );
  }

  const clients = v["mcp-client"] as string[] | undefined;
  for (const c of clients ?? []) {
    if (!MCP_TARGETS.some((t) => t.client === c)) {
      throw new UsageError(
        `--mcp-client must be one of ${MCP_TARGETS.map((t) => t.client).join(", ")}, got '${c}'`,
      );
    }
  }

  const flags: ScaffoldFlags = {};
  const set = <K extends keyof ScaffoldFlags>(key: K, value: ScaffoldFlags[K] | undefined) => {
    if (value !== undefined) flags[key] = value;
  };
  set("name", str("name"));
  set("botType", str("bot-type"));
  set("transport", v.transport as string[] | undefined);
  set("mode", str("mode"));
  set("stt", str("stt"));
  set("llm", str("llm"));
  set("tts", str("tts"));
  set("realtime", str("realtime"));
  set("video", str("video"));
  set("clientFramework", str("client-framework"));
  set("clientServer", str("client-server"));
  set("runtime", str("runtime"));
  set("recording", flag("recording"));
  set("transcription", flag("transcription"));
  set("videoInput", flag("video-input"));
  set("videoOutput", flag("video-output"));
  set("observability", flag("observability"));
  set("enableEval", flag("eval"));
  set("dockerfile", flag("dockerfile"));
  if (Object.keys(unsupported).length > 0) flags.unsupported = unsupported;
  for (const name of Object.keys(unsupported)) explicit.add(name);

  return {
    target: parsed.positionals[0] ?? null,
    overwriteGuide: v["overwrite-guide"] === true,
    mcp: flag("mcp") ?? true,
    mcpClients: clients as McpClient[] | undefined,
    dryRun: v["dry-run"] === true,
    listOptions: v["list-options"] === true,
    help: v.help === true,
    config: str("config") ?? null,
    flags,
    explicit,
  };
}

/** What happened to one guide file. */
export type GuideStatus = "wrote" | "overwrote" | "kept" | "kept-stale";

/** What `init` needs besides its arguments; `version` is stamped in the guide files and used in the project's dependencies. */
export type InitDeps = ScaffoldDeps;

/**
 * Provenance stamp appended to pipedog-owned guide files.
 *
 * The written guide is a static snapshot that otherwise looks like hand-written project docs.
 * The footer tells a later reader (human or agent) that it is generated and refreshable, and
 * which @pipedog/cli wrote it: so a re-run can spot a stale guide and nudge the developer to
 * refresh it.
 */
export function guideFooter(version: string = VERSION): string {
  return `\n<!-- Generated by \`pipedog init\` (@pipedog/cli ${version}). Run \`pipedog init --overwrite-guide\` to refresh. -->\n`;
}

/** The @pipedog/cli version recorded in a guide's footer, or `null` if unstamped. */
export function stampedVersion(text: string): string | null {
  return FOOTER_VERSION_RE.exec(text)?.[1] ?? null;
}

/**
 * Write one guide file under the uniform preserve-by-default rule.
 *
 * Absent: write it. Present: keep it (never clobber silently) unless `overwrite`. `stamped`
 * appends the provenance footer, so the file can be recognized and version-checked on a later
 * run; pass it for pipedog-owned guides (AGENTS.md, GETTING_STARTED.md), not the trivial
 * `@AGENTS.md` pointer in CLAUDE.md.
 *
 * Prints a per-file line and returns a status that the caller folds into a single refresh
 * summary.
 */
export function writeGuideFile(
  path: string,
  content: string,
  options: { stamped: boolean; overwrite: boolean; io: Io; version?: string },
): GuideStatus {
  const { io } = options;
  const version = options.version ?? VERSION;
  const body = options.stamped ? content + guideFooter(version) : content;

  if (!existsSync(path)) {
    writeFileSync(path, body, "utf8");
    io.out(`✔ Wrote ${path}`);
    return "wrote";
  }

  if (options.overwrite) {
    writeFileSync(path, body, "utf8");
    io.out(`✔ Overwrote ${path}`);
    return "overwrote";
  }

  // Keep the existing file. Surface whether it's a stale pipedog guide (worth a refresh nudge) or
  // one we don't own, so the developer knows why it was left alone.
  const stamped = stampedVersion(readFileSync(path, "utf8"));
  if (stamped !== null && stamped !== version) {
    io.out(`• Kept ${path} (written by @pipedog/cli ${stamped})`);
    return "kept-stale";
  }
  if (options.stamped && stamped === null) {
    io.out(`• Kept ${path} (your own file)`);
    return "kept";
  }
  io.out(`• Kept ${path}`);
  return "kept";
}

/**
 * Point the developer at `--overwrite-guide` when a re-run changed nothing.
 *
 * Keeps a preserve-everything run from reading as a silent no-op, and surfaces a stale guide
 * instead of letting it sit out of date quietly.
 */
export function printRefreshSummary(statuses: readonly GuideStatus[], io: Io): void {
  if (statuses.includes("kept-stale")) {
    io.out(
      "⚠  Your guide was written by an older pipedog. Run `pipedog init --overwrite-guide` to update it.",
    );
  } else if (statuses.length > 0 && statuses.every((s) => s.startsWith("kept"))) {
    io.out("Guide files already in place. Run `pipedog init --overwrite-guide` to refresh them.");
  }
}

/** Raised when a guide file can't be read or written. */
function fail(io: Io, message: string): never {
  io.err(`Error: ${message}`);
  throw new Exit(1);
}

/**
 * Write the core agent guide, AGENTS.md and CLAUDE.md, into a directory.
 *
 * Wanted on *every* path (coding agent, scaffold-now, quickstart), so they're written upfront.
 * Both follow the uniform rule (`writeGuideFile`): an existing file is kept unless `overwrite`.
 * AGENTS.md carries a provenance footer (so a re-run can spot a stale guide); CLAUDE.md is the
 * trivial `@AGENTS.md` pointer and is left unstamped.
 *
 * Returns the per-file statuses so the caller can follow up: a passive refresh nudge, or an
 * interactive offer to refresh. The developer guide (`GETTING_STARTED.md`) is written
 * separately, by `writeDeveloperGuide`, only on the coding-agent path.
 *
 * @throws Exit(1) On a read or write error.
 */
export function writeAgentGuide(
  targetDir: string,
  overwrite: boolean,
  deps: InitDeps,
): GuideStatus[] {
  let agents: string;
  let claude: string;
  try {
    agents = readAsset(`agent_templates/${AGENTS_FILE}`);
    claude = readAsset(`agent_templates/${CLAUDE_FILE}`);
  } catch (e) {
    // Bundled data missing: a packaging regression.
    return fail(deps.io, `bundled agent guide not found: ${e instanceof Error ? e.message : e}`);
  }
  try {
    mkdirSync(targetDir, { recursive: true });
    const common = { overwrite, io: deps.io, ...(deps.version ? { version: deps.version } : {}) };
    return [
      writeGuideFile(join(targetDir, AGENTS_FILE), agents, { ...common, stamped: true }),
      writeGuideFile(join(targetDir, CLAUDE_FILE), claude, { ...common, stamped: false }),
    ];
  } catch (e) {
    return fail(deps.io, `writing files: ${e instanceof Error ? e.message : e}`);
  }
}

/**
 * Write GETTING_STARTED.md (from-scratch developer onboarding) into a directory.
 *
 * Written only on the coding-agent path, where the developer is about to commission a build. It
 * does *not* fit a project that's just been scaffolded (`Scaffold a runnable bot now` or
 * `pipedog init quickstart`): there the bot already exists and the scaffold's README is the
 * start-here. Follows the same preserve-by-default rule as the rest of the guide.
 *
 * @throws Exit(1) On a read or write error.
 */
export function writeDeveloperGuide(targetDir: string, overwrite: boolean, deps: InitDeps): void {
  let src: string;
  try {
    src = readAsset(`agent_templates/${GETTING_STARTED_FILE}`);
  } catch (e) {
    fail(deps.io, `bundled agent guide not found: ${e instanceof Error ? e.message : e}`);
  }
  try {
    mkdirSync(targetDir, { recursive: true });
    writeGuideFile(join(targetDir, GETTING_STARTED_FILE), src, {
      stamped: true,
      overwrite,
      io: deps.io,
      ...(deps.version ? { version: deps.version } : {}),
    });
  } catch (e) {
    fail(deps.io, `writing files: ${e instanceof Error ? e.message : e}`);
  }
}

/**
 * Register the pipedog docs MCP server with the coding agents, in the project.
 *
 * Idempotent and quick, so it runs without asking: the guide this command just wrote tells the
 * agent to use the docs tools, and registering is what makes that possible. Never fatal: this is
 * setup for a tool the developer can also configure by hand, so a failure here must not fail the
 * command that scaffolded their project.
 */
export function setupMcp(
  targetDir: string,
  options: { clients?: readonly McpClient[] | undefined; overwrite: boolean },
  io: Io,
): void {
  try {
    const results = registerMcp(targetDir, {
      ...(options.clients ? { clients: options.clients } : {}),
      overwrite: options.overwrite,
    });
    for (const line of describeMcpResults(results)) io.out(line);
    if (results.some((r) => r.status === "added" || r.status === "updated")) {
      io.out(
        "  MCP servers load when a coding session starts: open yours in this directory after init.",
      );
    }
  } catch (e) {
    io.out(
      `\n  Set up the docs MCP server for your coding agent with:\n      claude mcp add pipedog -- npx -y @pipedog/mcp\n  (${e instanceof Error ? e.message : e})`,
    );
  }
}

/**
 * Print the guidance shown when the developer keeps the coding-agent path.
 *
 * Names the project directory so the developer knows where to open their session, except when
 * init targeted the current directory (`pipedog init .`), where "here" reads better than "in .".
 */
export function printReady(targetDir: string, io: Io): void {
  const where = resolve(targetDir) === resolve(io.cwd) ? "here" : `in ${targetDir}`;
  io.out(
    `\nYour project is ready.\n\nRead ${GETTING_STARTED_FILE} for how to prompt your agent, then open a coding session ${where} to start building.`,
  );
}

/** Ask whether to refresh a guide from an older pipedog; true if the guide was refreshed. */
async function offerRefresh(
  targetDir: string,
  deps: InitDeps,
  prompter: Prompter,
): Promise<boolean> {
  const refresh = await prompter.confirm(
    "A guide file is from an older pipedog. Refresh the guide files now?",
    true,
  );
  // `null` on Ctrl-C: treat anything but an explicit yes as "keep".
  if (refresh) {
    writeAgentGuide(targetDir, true, deps);
    return true;
  }
  return false;
}

/**
 * Ask whether to build with a coding agent or scaffold a runnable bot now.
 *
 * The coding-agent path adds the developer guide (GETTING_STARTED.md) and points the developer at
 * their coding session. It's also the default when there's no interactive terminal (automation,
 * tests, piped input) or when re-running in an already-scaffolded project to refresh the guide.
 * The scaffold path runs the wizard in place and skips the developer guide: the scaffold's README
 * is the start-here for a built bot.
 */
async function routeBuildMethod(
  targetDir: string,
  args: { overwriteGuide: boolean; mcp: boolean; mcpClients: McpClient[] | undefined },
  deps: InitDeps,
  prompter: Prompter,
): Promise<void> {
  const { io } = deps;
  const agentPath = () => {
    writeDeveloperGuide(targetDir, args.overwriteGuide, deps);
    if (args.mcp)
      setupMcp(targetDir, { clients: args.mcpClients, overwrite: args.overwriteGuide }, io);
    printReady(targetDir, io);
  };
  const alreadyScaffolded = existsSync(join(targetDir, "server"));
  if (alreadyScaffolded || !io.interactive) {
    agentPath();
    return;
  }

  const choice = await prompter.select("How do you want to build?", [
    { label: "Build with a coding agent (recommended)", value: "agent" },
    { label: "Scaffold a runnable bot now", value: "scaffold" },
  ]);

  // `null` on Ctrl-C: fall through to the safe agent path.
  if (choice !== "scaffold") {
    agentPath();
    return;
  }

  // Scaffold now: run the wizard in place. The scaffold lands in the same directory that already
  // holds AGENTS.md/CLAUDE.md (in-place mode preserves CLAUDE.md), and its README carries the
  // start-here guidance, so no GETTING_STARTED.md here.
  try {
    await scaffoldInteractive(targetDir, basename(resolve(targetDir)), true, { ...deps, prompter });
    if (args.mcp)
      setupMcp(targetDir, { clients: args.mcpClients, overwrite: args.overwriteGuide }, io);
  } catch (e) {
    handleScaffoldError(e, io);
  }
}

/** Report a failure of the scaffolding step and end with exit code 1. */
function handleScaffoldError(e: unknown, io: Io): never {
  if (e instanceof Exit) throw e;
  if (e instanceof ProjectCancelledError) {
    io.out("\nProject creation cancelled.");
    throw new Exit(1);
  }
  if (e instanceof FileExistsError) {
    io.err(`\nError: ${e.message}`);
    throw new Exit(1);
  }
  io.err(`\nError creating project: ${e instanceof Error ? e.message : String(e)}`);
  throw new Exit(1);
}

/**
 * `pipedog init quickstart`: the canned quickstart, with the coding-agent guide.
 *
 * Writes the agent guide into `pipedog-quickstart/` and scaffolds the quickstart bot in place
 * there, so the learner's first project is both runnable and set up for coding agents.
 * Non-interactive: it's a fixed preset, so there's no build-method question.
 *
 * Skips `GETTING_STARTED.md` (the from-scratch developer onboarding): the bot already exists, so
 * the scaffold's README is the start-here.
 */
async function initQuickstart(args: InitArgs, deps: InitDeps): Promise<void> {
  const targetDir = resolve(deps.io.cwd, QUICKSTART_DIR);
  // AGENTS.md + CLAUDE.md only: writeAgentGuide never writes GETTING_STARTED.md. Quickstart is a
  // fixed, non-interactive preset, so a stale guide just gets the nudge.
  printRefreshSummary(writeAgentGuide(targetDir, args.overwriteGuide, deps), deps.io);
  try {
    await scaffoldQuickstart({ dest: targetDir, inPlace: true, deps });
    if (args.mcp)
      setupMcp(targetDir, { clients: args.mcpClients, overwrite: args.overwriteGuide }, deps.io);
  } catch (e) {
    handleScaffoldError(e, deps.io);
  }
}

/**
 * Whether scaffold options were given, which switch `init` to non-interactive scaffolding.
 *
 * A value on any of these (or `--config`) means "build the project now" rather than just
 * writing the guide and prompting.
 */
export function scaffoldRequested(args: InitArgs): boolean {
  const f = args.flags;
  return (
    args.config !== null ||
    (f.transport?.length ?? 0) > 0 ||
    [f.name, f.botType, f.mode, f.stt, f.llm, f.tts, f.realtime, f.video].some(
      (v) => v !== undefined,
    )
  );
}

/**
 * Write the agent guide and scaffold the project in place from flags or a config file.
 *
 * The in-place sibling of the wizard path (`routeBuildMethod`): same directory, no
 * `GETTING_STARTED.md` (the scaffold's README is the start-here). With no positional target we
 * scaffold into the current directory rather than prompting, so an automated run (a coding agent
 * that omits the `.`) never hangs.
 *
 * The scaffold config is resolved and validated *before* the guide is written, so an invalid
 * invocation (or `--dry-run`) fails without leaving a half-initialized directory.
 */
async function scaffoldNonInteractive(args: InitArgs, deps: InitDeps): Promise<void> {
  const { io } = deps;
  const targetDir = resolve(io.cwd, args.target ?? ".");
  if (existsSync(targetDir) && !statSync(targetDir).isDirectory()) {
    io.err(`Error: ${targetDir} exists and is not a directory.`);
    throw new Exit(1);
  }
  try {
    // Validate first: this exits non-zero on a bad config, or zero on --dry-run, before anything
    // is written. Only a fully valid, non-dry-run invocation reaches the writes.
    const config = resolveScaffoldConfig({
      derivedName: basename(targetDir) || "pipedog-app",
      dryRun: args.dryRun,
      config: args.config ? resolve(io.cwd, args.config) : null,
      flags: args.flags,
      explicit: args.explicit,
      io,
    });
    writeAgentGuide(targetDir, args.overwriteGuide, deps);
    await generateScaffold(config, { dest: targetDir, inPlace: true, deps });
    if (args.mcp)
      setupMcp(targetDir, { clients: args.mcpClients, overwrite: args.overwriteGuide }, io);
  } catch (e) {
    handleScaffoldError(e, io);
  }
}

/**
 * Run `pipedog init`.
 *
 * @param argv The arguments after `init`.
 * @returns The process's exit code.
 */
export async function initCommand(argv: readonly string[], deps: InitDeps): Promise<number> {
  const { io } = deps;
  try {
    let args: InitArgs;
    try {
      args = parseInitArgs(argv);
    } catch (e) {
      if (e instanceof UsageError) {
        io.err(
          `Usage: pipedog init [OPTIONS] [TARGET]\nTry 'pipedog init --help' for help.\n\nError: ${e.message}`,
        );
        return 2;
      }
      throw e;
    }
    if (args.help) {
      io.out(INIT_HELP.trimEnd());
      return 0;
    }
    if (args.listOptions) listOptionsCallback(io);

    // `pipedog init quickstart`: scaffold the canned bot in place, with the coding-agent guide.
    if (args.target === "quickstart") {
      // quickstart is a fixed preset: scaffold flags don't apply. Say so instead of silently
      // ignoring them.
      if ([...args.explicit].length > 0) {
        io.out("Note: `quickstart` is a fixed preset; ignoring the scaffold options you passed.");
      }
      await initQuickstart(args, deps);
      return 0;
    }

    if (scaffoldRequested(args)) {
      await scaffoldNonInteractive(args, deps);
      return 0;
    }

    // No scaffold options: write the guide and route to a build method. No argument: prompt for
    // the directory. `target` is just a path: `.` sets up the current directory, any other value
    // names a folder (created below if it doesn't exist).
    const prompter = deps.prompter ?? new ClackPrompter();
    let target = args.target;
    if (target === null) {
      if (io.interactive) {
        const answer = await prompter.text("Project directory", { initialValue: "pipedog-bot" });
        if (answer === null) throw new ProjectCancelledError();
        target = answer.trim();
      } else {
        // Never prompt without a terminal: a piped run would hang.
        target = ".";
      }
    }

    // Validate before any write so a failure never leaves a half-initialized directory.
    const targetDir = resolve(io.cwd, target || ".");
    if (existsSync(targetDir) && !statSync(targetDir).isDirectory()) {
      io.err(`Error: ${targetDir} exists and is not a directory.`);
      return 1;
    }

    const statuses = writeAgentGuide(targetDir, args.overwriteGuide, deps);
    // A re-run on a guide from an older pipedog: interactively offer to refresh it now (the
    // expected payoff of re-running), otherwise fall back to the printed nudge.
    let overwriteGuide = args.overwriteGuide;
    if (!overwriteGuide && statuses.includes("kept-stale") && io.interactive) {
      overwriteGuide = await offerRefresh(targetDir, deps, prompter);
    } else {
      printRefreshSummary(statuses, io);
    }
    await routeBuildMethod(targetDir, { ...args, overwriteGuide }, deps, prompter);
    return 0;
  } catch (e) {
    if (e instanceof Exit) return e.code;
    if (e instanceof ProjectCancelledError) {
      io.out("\nProject creation cancelled.");
      return 1;
    }
    throw e;
  }
}
