// Builds the committed artifacts:
//   1. cargo build --release --target wasm32-unknown-unknown   (opt-level "z", LTO, panic=abort)
//   2. wasm-opt -Oz (binaryen; from PATH, else `npx -p binaryen`) unless --no-opt
//      -> wasm/sentencex.wasm
//   3. src/wasm_bytes.ts: the same bytes as base64, so the default entry can
//      compile the module synchronously without any file or network access.
//
// Needs: rustup target add wasm32-unknown-unknown

import { copyFileSync, readFileSync, statSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const built = `${root}rust/target/wasm32-unknown-unknown/release/pipecat_sentencex_wasm.wasm`;
const out = `${root}wasm/sentencex.wasm`;
const bytesModule = `${root}src/wasm_bytes.ts`;

function run(cmd: string[]): boolean {
  const res = Bun.spawnSync(cmd, { cwd: root, stdout: "inherit", stderr: "inherit" });
  return res.exitCode === 0;
}

if (
  !run([
    "cargo",
    "build",
    "--manifest-path",
    "rust/Cargo.toml",
    "--release",
    "--target",
    "wasm32-unknown-unknown",
  ])
) {
  process.exit(1);
}
const rawSize = statSync(built).size;

// Only the features rustc already emits for wasm32-unknown-unknown.
const opt = [
  "-Oz",
  "--enable-bulk-memory",
  "--enable-nontrapping-float-to-int",
  "--enable-sign-ext",
  "--enable-mutable-globals",
  "--enable-multivalue",
  "--enable-reference-types",
  built,
  "-o",
  out,
];
let optimized = false;
if (!process.argv.includes("--no-opt")) {
  optimized =
    (Bun.which("wasm-opt") !== null && run(["wasm-opt", ...opt])) ||
    run(["npx", "--yes", "-p", "binaryen@132.0.0", "wasm-opt", ...opt]);
  if (!optimized) console.warn("wasm-opt unavailable; copying the unoptimized build");
}
if (!optimized) copyFileSync(built, out);

const wasm = readFileSync(out);
const base64 = wasm.toString("base64");
writeFileSync(
  bytesModule,
  `// Copyright (c) 2026, pipecat-ts contributors
// SPDX-License-Identifier: BSD-2-Clause

// GENERATED by scripts/build-wasm.ts from wasm/sentencex.wasm. Do not edit.
// The module's bytes as base64, so the default entry can compile it synchronously.

/** Byte length of wasm/sentencex.wasm. */
export const WASM_SIZE = ${wasm.length};

/** wasm/sentencex.wasm, base64-encoded. */
export const WASM_BASE64 =
  "${base64}";
`,
);

console.log(
  `wasm/sentencex.wasm: ${wasm.length} bytes (cargo: ${rawSize}${optimized ? ", after wasm-opt -Oz" : ""}); wrote src/wasm_bytes.ts`,
);
