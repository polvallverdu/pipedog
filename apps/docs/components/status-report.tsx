import { readFileSync } from "node:fs";
import path from "node:path";
import { Markdown } from "fumadocs-core/content/md";
import { remarkGfm } from "fumadocs-core/mdx-plugins";
import defaultMdxComponents from "fumadocs-ui/mdx";

/** Escape `<` outside inline code, so notes like `Promise<T>` aren't read as HTML. */
function escapeAngles(md: string): string {
  return md
    .split("\n")
    .map((line) =>
      line
        .split("`")
        .map((part, i) => (i % 2 === 0 ? part.replaceAll("<", "&lt;") : part))
        .join("`"),
    )
    .join("\n");
}

/** Renders porting/STATUS.md (generated by `bun run port:status`) at build time. */
export function StatusReport() {
  const file = path.resolve(process.cwd(), "../../porting/STATUS.md");
  // Drop the document's own H1: the page has a title already.
  const md = readFileSync(file, "utf8").replace(/^# .*\n/, "");
  return (
    <Markdown remarkPlugins={[remarkGfm]} components={defaultMdxComponents}>
      {escapeAngles(md)}
    </Markdown>
  );
}
