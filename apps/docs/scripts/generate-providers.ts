// Writes the provider pages that come from data/providers.ts: one short "coming soon" page per
// upcoming provider, the overview and category index pages, the long-tail list, and the
// meta.json files that order the sidebar. The ported pages are written by hand and only listed.
// Run with `bun run providers:generate` (in apps/docs); `--check` fails if a file is stale.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import {
  type Category,
  longTail,
  type PortedPage,
  ported,
  type Section,
  sections,
  type UpcomingPage,
  unportedVariants,
  upcoming,
} from "../data/providers.ts";

const docs = join(import.meta.dir, "../content/docs");
const repo = "https://github.com/polvallverdu/pipedog";
const upstreamRepo = "https://github.com/pipecat-ai/pipecat/blob/main/src/pipecat";
const upstreamDocs = "https://docs.pipecat.ai/api-reference/server/services";
const GENERATED = "{/* Generated by scripts/generate-providers.ts from data/providers.ts. */}";

/** Upstream module path -> the pipedog package it is (or will be) ported to. */
const manifest = JSON.parse(
  await readFile(join(import.meta.dir, "../../../porting/manifest.json"), "utf8"),
) as {
  modules: { upstream: string; package: string }[];
};
const packageOf = new Map(manifest.modules.map((m) => [m.upstream, m.package]));

function plannedPackage(page: UpcomingPage): string | undefined {
  for (const module of page.modules) {
    const pkg = packageOf.get(`src/pipecat/${module}`);
    if (pkg) return pkg;
  }
  return undefined;
}

const categories: Category[] = ["llm", "stt", "tts", "s2s", "image", "video"];
const check = process.argv.includes("--check");
const stale: string[] = [];

/** The folder a section's pages live in, under content/docs. */
function folder(section: Section): string {
  return section === "transports" || section === "serializers" ? section : `services/${section}`;
}

function pageUrl(section: Section, slug: string): string {
  return `/docs/${folder(section)}/${slug}`;
}

function upstreamPage(page: UpcomingPage): string {
  return (
    page.upstreamUrl ?? `${upstreamDocs}/${sections[page.section].upstreamFolder}/${page.slug}`
  );
}

function byName<T extends { name: string }>(items: T[]): T[] {
  return [...items].sort((a, b) => a.name.localeCompare(b.name));
}

const code = (names: string[]) => names.map((name) => `\`${name}\``).join(", ");

const biome = join(import.meta.dir, "../../../node_modules/.bin/biome");

/** Format JSON the way `bun run lint` wants it. */
async function biomeFormat(file: string, content: string): Promise<string> {
  const proc = Bun.spawn([biome, "format", `--stdin-file-path=${file}`], {
    stdin: new Blob([content]),
    stdout: "pipe",
  });
  const formatted = await new Response(proc.stdout).text();
  if ((await proc.exited) !== 0) throw new Error(`biome format failed for ${file}`);
  return formatted;
}

async function write(path: string, raw: string): Promise<void> {
  const file = join(docs, path);
  const content = path.endsWith(".json") ? await biomeFormat(file, raw) : raw;
  if (check) {
    const current = await readFile(file, "utf8").catch(() => null);
    if (current !== content) stale.push(relative(process.cwd(), file));
    return;
  }
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, content);
}

const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;

function frontmatter(title: string, description: string): string {
  return `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n`;
}

function issueLinks(page: UpcomingPage): { open: string; search: string } {
  const params = new URLSearchParams({
    template: "feature_request.yml",
    title: `Port ${page.name} (${page.classes.join(", ")})`,
    kind: "Port an upstream module",
    upstream: page.modules.map((module) => `src/pipecat/${module}`).join(", "),
  });
  return {
    open: `${repo}/issues/new?${params}`,
    search: `${repo}/issues?${new URLSearchParams({ q: `is:issue ${page.name}` })}`,
  };
}

function upcomingPage(page: UpcomingPage): string {
  const { open, search } = issueLinks(page);
  const pkg = plannedPackage(page);
  return `${frontmatter(page.name, `${page.about} Not ported to pipedog yet.`)}
${GENERATED}

<Callout type="warn" title="Coming soon">
  ${page.name} isn't ported to pipedog yet. It is available in Pipecat (Python), and its pipedog
  port will keep the same class names and options. [Ask for it, or upvote the request](${search}).
</Callout>

## What it is

${page.about}

Upstream, it's ${page.classes.length > 1 ? "these classes" : "this class"}: ${code(page.classes)}, in
${page.modules.map((module) => `[\`${module}\`](${upstreamRepo}/${module})`).join(" and ")}.

${pkg ? `Its pipedog package will be \`${pkg}\`.\n\n` : ""}- [Pipecat's ${page.name} page](${upstreamPage(page)})

## Get it ported

- [Search the issues](${search}) for a request, and upvote it with a reaction.
- If there's none, [open a port request](${open}).
- Or port it yourself: the [contributing guide](/docs/contributing) explains how modules are ported,
  test by test. The [porting status](/docs/contributing/status) lists what's done.

Until then, see what is ported in [${sections[page.section].title}](/docs/${folder(page.section)}).
`;
}

function portedRows(section: Section): string[] {
  return ported[section].map(
    (page: PortedPage) =>
      `| [${page.name}](${pageUrl(section, page.slug)}) | ${code(page.classes)} | \`${page.pkg}\` | Ported |`,
  );
}

function upcomingRows(section: Section): string[] {
  return byName(upcoming.filter((page) => page.section === section)).map(
    (page) =>
      `| [${page.name}](${pageUrl(section, page.slug)}) | ${code(page.classes)} | | Coming soon |`,
  );
}

function table(section: Section): string {
  return [
    "| Provider | Classes | Package | Status |",
    "|---|---|---|---|",
    ...portedRows(section),
    ...upcomingRows(section),
  ].join("\n");
}

function sectionMeta(section: Section, withIndex: boolean): string {
  const soon = byName(upcoming.filter((page) => page.section === section)).map((page) => page.slug);
  return json({
    title: sections[section].title,
    pages: [
      ...(withIndex ? ["index"] : []),
      ...ported[section].map((page) => page.slug),
      ...(soon.length ? ["---Coming soon---", ...soon] : []),
    ],
  });
}

const intros: Record<Section, string> = {
  llm: "An LLM service takes the conversation context (an `LLMContext`, through the context aggregators) and streams the model's response as text frames, with function calls.",
  stt: "A speech-to-text service takes the user's audio frames and pushes `TranscriptionFrame`s (and `InterimTranscriptionFrame`s while the user speaks).",
  tts: "A text-to-speech service takes the bot's text frames and pushes audio frames, with word timestamps where the provider sends them.",
  s2s: "A speech-to-speech service replaces the STT, LLM and TTS trio with one realtime model: audio in, audio and text out, with function calls.",
  image:
    "An image generation service takes a text prompt and pushes the generated image as a frame.",
  video:
    "A video service animates an avatar that speaks the bot's audio, and sends its video to the user.",
  transports:
    "A transport moves audio, video and messages between the user and the pipeline: `transport.input()` goes first in a pipeline and `transport.output()` near the end.",
  serializers:
    "A serializer converts frames to and from a wire format, so a WebSocket transport can speak a client's or a telephony provider's protocol.",
};

function sectionIndex(section: Section): string {
  const info = sections[section];
  return `${frontmatter(info.title, info.description)}
${GENERATED}

${intros[section]}

${table(section)}

Pipecat's [${info.title.toLowerCase()} reference](${upstreamDocs}/${info.upstreamFolder}) lists every upstream provider. Those not in this table are on [Other upstream providers](/docs/services/other-upstream).
`;
}

function servicesIndex(): string {
  const parts = categories.map(
    (category) =>
      `## ${sections[category].title}\n\n${sections[category].description} [All ${sections[category].title.toLowerCase()} services](/docs/services/${category}).\n\n${table(category)}`,
  );
  const portedCount = categories.reduce((n, category) => n + ported[category].length, 0);
  return `${frontmatter(
    "Supported services",
    "Every pipedog service by category: ported, and coming soon from Pipecat.",
  )}
${GENERATED}

Services are frame processors that call an AI provider. pipedog ports them from Pipecat with the same
class names and options (in camelCase), one package per provider: \`@pipedog/openai\`,
\`@pipedog/deepgram\` and so on. ${portedCount} service pages are ported so far. The "coming soon"
pages link to Pipecat's docs and to a port request.

Each service page follows the same layout as Pipecat's: overview, installation, configuration
options, settings, usage, and runtime notes for Bun, Node, Deno and Cloudflare Workers.

${parts.join("\n\n")}

## Not listed here

Pipecat has more providers than this page lists. See [Other upstream providers](/docs/services/other-upstream)
for the rest, and the [porting status](/docs/contributing/status) for module-level detail.
`;
}

function otherUpstream(): string {
  const rows = byName(longTail).map(
    (provider) =>
      `| ${provider.name} | ${provider.kinds.join(", ")} | ${code(provider.classes)} | [\`services/${provider.folder}\`](${upstreamRepo}/services/${provider.folder}) |`,
  );
  const variants = unportedVariants.map(
    (variant) =>
      `| ${variant.name} | ${code(variant.classes)} | ${variant.modules.map((module) => `[\`${module}\`](${upstreamRepo}/${module})`).join(", ")} |`,
  );
  return `${frontmatter(
    "Other upstream providers",
    "Pipecat services that aren't ported to pipedog yet and have no page of their own here.",
  )}
${GENERATED}

These Pipecat services aren't ported yet. Each will keep its upstream class names when it is. To ask
for one, [open a port request](${repo}/issues/new?template=feature_request.yml) or upvote an
existing one in the [issues](${repo}/issues).

| Provider | Kind | Upstream classes | Upstream source |
|---|---|---|---|
${rows.join("\n")}

## Variants of ported providers

These providers are ported, but these classes aren't yet:

| Variant | Upstream classes | Upstream source |
|---|---|---|
${variants.join("\n")}
`;
}

for (const page of upcoming) {
  if (ported[page.section].some((p) => p.slug === page.slug)) {
    throw new Error(`${page.section}/${page.slug} is both ported and upcoming`);
  }
  await write(`${folder(page.section)}/${page.slug}.mdx`, upcomingPage(page));
}
for (const category of categories) {
  await write(`services/${category}/index.mdx`, sectionIndex(category));
  await write(`services/${category}/meta.json`, sectionMeta(category, true));
}
for (const section of ["transports", "serializers"] as const) {
  await write(`${section}/index.mdx`, sectionIndex(section));
  await write(`${section}/meta.json`, sectionMeta(section, true));
}
await write("services/index.mdx", servicesIndex());
await write("services/other-upstream.mdx", otherUpstream());
await write(
  "services/meta.json",
  json({ title: "Services", pages: ["index", ...categories, "other-upstream"] }),
);

if (stale.length) {
  console.error(
    `generate-providers: stale, run \`bun run providers:generate\`:\n  ${stale.join("\n  ")}`,
  );
  process.exit(1);
}
console.log(
  check
    ? "generate-providers: up to date"
    : `generate-providers: ${upcoming.length} coming-soon pages, ${categories.length + 3} indexes`,
);
