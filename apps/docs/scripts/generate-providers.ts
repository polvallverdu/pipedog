function sectionIndex(section: Section): string {
  const info = sections[section];
  return `${frontmatter(info.title, info.description)}
${GENERATED}

${intros[section]}

${table(section)}

Pipecat's [${info.title.toLowerCase()} reference](${upstreamDocs}/${info.upstreamFolder}) lists every upstream provider. Those not in this table are on [Other upstream providers](/docs/services/other-upstream).
`;
}

function servicesIndex(): string {
  const parts = categories.map(
    (category) =>
      `## ${sections[category].title}\n\n${sections[category].description} [All ${sections[category].title.toLowerCase()} services](/docs/services/${category}).\n\n${table(category)}`,
  );
  const portedCount = categories.reduce((n, category) => n + ported[category].length, 0);
  return `${frontmatter(
    "Supported services",
    "Every pipedog service by category: ported, and coming soon from Pipecat.",
  )}
${GENERATED}

Services are frame processors that call an AI provider. pipedog ports them from Pipecat with the same
class names and options (in camelCase), one package per provider: \`@pipedog/openai\`,
\`@pipedog/deepgram\` and so on. ${portedCount} service pages are ported so far. The "coming soon"
pages link to Pipecat's docs and to a port request.

Each service page follows the same layout as Pipecat's: overview, installation, configuration
options, settings, usage, and runtime notes for Bun, Node, Deno and Cloudflare Workers.

${parts.join("\n\n")}

## Not listed here

Pipecat has more providers than this page lists. See [Other upstream providers](/docs/services/other-upstream)
for the rest, and the [porting status](/docs/contributing/status) for module-level detail.
`;
}

function otherUpstream(): string {
  const rows = byName(longTail).map(
    (provider) =>
      `| ${provider.name} | ${provider.kinds.join(", ")} | ${code(provider.classes)} | [\`services/${provider.folder}\`](${upstreamRepo}/services/${provider.folder}) |`,
  );
  const variants = unportedVariants.map(
    (variant) =>
      `| ${variant.name} | ${code(variant.classes)} | ${variant.modules.map((module) => `[\`${module}\`](${upstreamRepo}/${module})`).join(", ")} |`,
  );
  return `${frontmatter(
    "Other upstream providers",
    "Pipecat services that aren't ported to pipedog yet and have no page of their own here.",
  )}
${GENERATED}

These Pipecat services aren't ported yet. Each will keep its upstream class names when it is. To ask
for one, [open a port request](${repo}/issues/new?template=feature_request.yml) or upvote an
existing one in the [issues](${repo}/issues).

| Provider | Kind | Upstream classes | Upstream source |
|---|---|---|---|
${rows.join("\n")}

## Variants of ported providers

These providers are ported, but these classes aren't yet:

| Variant | Upstream classes | Upstream source |
|---|---|---|
${variants.join("\n")}
`;
}

for (const page of upcoming) {
  if (ported[page.section].some((p) => p.slug === page.slug)) {
    throw new Error(`${page.section}/${page.slug} is both ported and upcoming`);
  }
  await write(`${folder(page.section)}/${page.slug}.mdx`, upcomingPage(page));
}
for (const page of compatibleLlm) {
  await write(`services/llm/${page.slug}.mdx`, compatibleLlmPage(page));
}
for (const category of categories) {
  await write(`services/${category}/index.mdx`, sectionIndex(category));
  await write(`services/${category}/meta.json`, sectionMeta(category, true));
}
for (const section of ["audio", "transports", "serializers"] as const) {
  await write(`${section}/index.mdx`, sectionIndex(section));
  await write(`${section}/meta.json`, sectionMeta(section, true));
}
await write("services/index.mdx", servicesIndex());
await write("services/other-upstream.mdx", otherUpstream());
await write(
  "services/meta.json",
  json({ title: "Services", pages: ["index", ...categories, "other-upstream"] }),
);

if (stale.length) {
  console.error(
    `generate-providers: stale, run \`bun run providers:generate\`:\n  ${stale.join("\n  ")}`,
  );
  process.exit(1);
}
console.log(
  check
    ? "generate-providers: up to date"
    : `generate-providers: ${upcoming.length} coming-soon pages, ${compatibleLlm.length} OpenAI-compatible LLM pages, ${categories.length + 3} indexes`,
);
